export function calculateSideHustleType(answers) {
    const scores = {
        creator: 0,
        consultant: 0,
        builder: 0,
        connector: 0
    };
    if (answers.monetization_style === 'products' || answers.monetization_style === 'content') {
        scores.creator += 2;
    }
    if (answers.monetization_style === 'services') {
        scores.consultant += 2;
    }
    if (answers.social_preference === 'high_touch' || answers.social_preference === 'selective') {
        scores.consultant += 1;
        scores.connector += 1;
    }
    if (answers.social_preference === 'minimal') {
        scores.builder += 2;
    }
    if (answers.social_preference === 'community') {
        scores.creator += 1;
        scores.connector += 1;
    }
    if (answers.skill_leverage === 'technical') {
        scores.builder += 2;
        scores.consultant += 1;
    }
    if (answers.skill_leverage === 'creative') {
        scores.creator += 2;
    }
    if (answers.skill_leverage === 'teaching') {
        scores.creator += 1;
        scores.consultant += 1;
    }
    if (answers.skill_leverage === 'connecting') {
        scores.connector += 2;
    }
    if (answers.growth_ambition === 'empire' || answers.growth_ambition === 'replace_job') {
        scores.builder += 1;
    }
    if (answers.growth_ambition === 'passion') {
        scores.creator += 1;
    }
    if (answers.risk_tolerance === 'high_risk') {
        scores.builder += 1;
    }
    if (answers.risk_tolerance === 'security_first' || answers.risk_tolerance === 'steady_growth') {
        scores.consultant += 1;
    }
    return Object.keys(scores).reduce((best, key)=>scores[best] >= scores[key] ? best : key);
}
